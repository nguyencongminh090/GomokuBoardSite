  let lang = 'vi';

  function t(key, params) {
    const v = STRINGS[lang][key] ?? STRINGS.en[key];
    if (v === undefined) return key;
    return typeof v === 'function' ? v(params || {}) : v;
  }

  function setLang(next) {
    lang = STRINGS[next] ? next : 'vi';
    document.documentElement.lang = lang;
    document.title = t('app.title');
  }

  // Translates static markup: data-i18n (text), data-i18n-html (trusted markup from STRINGS)
  // and data-i18n-attr="title:key;aria-label:key".
  function apply(root = document) {
    for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
    for (const el of root.querySelectorAll('[data-i18n-attr]')) {
      for (const pair of el.dataset.i18nAttr.split(';')) {
        if (!pair.trim()) continue;
        const [attr, key] = pair.split(':');
        el.setAttribute(attr.trim(), t(key.trim()));
      }
    }
  }

  G.i18n = {
    STRINGS,
    LANGS: Object.keys(STRINGS),
    t,
    setLang,
    apply,
    get lang() { return lang; },
    get locale() { return t('locale'); },
  };
