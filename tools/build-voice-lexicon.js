// Builds js/voice-lexicon.js from the Vietnamese dictionary: node tools/build-voice-lexicon.js [dataset/Viet74K.txt]
// Whisper hears the right sound and writes a different real syllable ("xáu" for "sáu", "chăm" for "trăm"). The dictionary
// lists every real syllable, so each one that sounds like exactly one spoken digit or number word becomes an alias of it.
// Syllables that sound like two different targets are left out, and so are column letters (a wrong column is silent and a
// wrong cell is worse than none).
'use strict';

const fs = require('fs');
const path = require('path');

global.window = {};
eval(fs.readFileSync(path.join(__dirname, '..', 'js', 'voice.js'), 'utf8'));
const V = window.Gomoku.voice;

// The sound of a syllable, tone marks already removed: the merges Vietnamese speakers (and Whisper) mix up.
const INITIALS = [['ngh', 'n'], ['ng', 'n'], ['gi', 'z'], ['tr', 'c'], ['ch', 'c'], ['nh', 'l'], ['d', 'z'], ['r', 'z'], ['x', 's'], ['n', 'l']];
const FINALS = [['ng', 'n'], ['nh', 'n'], ['ch', 'c'], ['t', 'c']];

function sound(word) {
  let s = word;
  for (const [from, to] of INITIALS) {
    if (s.startsWith(from)) { s = to + s.slice(from.length); break; }
  }
  for (const [from, to] of FINALS) {
    if (s.length > from.length && s.endsWith(from)) { s = s.slice(0, -from.length) + to; break; }
  }
  return s;
}

// Every spoken target and what it means; the id decides when two sounds are the same word (bon and tu are both 4).
const targets = new Map(); // folded word -> id
const { DIGITS, STRUCTURE } = V.vocabulary;
for (const [w, d] of Object.entries(DIGITS)) targets.set(w, 'd' + d);
for (const w of STRUCTURE) targets.set(w, 's' + w);

const bySound = new Map(); // sound -> Set of ids
for (const [w, id] of targets) {
  const k = sound(w);
  if (!bySound.has(k)) bySound.set(k, new Set());
  bySound.get(k).add(id);
}

const file = process.argv[2] || path.join(__dirname, '..', 'dataset', 'Viet74K.txt');
const syllables = new Set();
for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
  const w = line.trim();
  if (w && !/[\s-]/.test(w)) syllables.add(V.normalize(w));
}

const aliases = {};
for (const w of [...syllables].sort()) {
  if (targets.has(w) || w.length < 2) continue;
  const ids = bySound.get(sound(w));
  if (!ids || ids.size !== 1) continue;
  const id = [...ids][0];
  const target = [...targets].find(([, tid]) => tid === id);
  // Prefer the plain spelling of the target ("sau" for d6, "muoi" for muoi).
  aliases[w] = target[0];
}

const lines = Object.keys(aliases).map((w) => `${w}:${aliases[w]}`);
const out = `// Generated by tools/build-voice-lexicon.js from dataset/Viet74K.txt. Do not edit.\n`
  + `// Syllables that sound like one spoken number word -> that word (tone marks removed).\n`
  + `(function (G) {\n  'use strict';\n  G.voiceLexicon = '${lines.join(' ')}'.split(' ').reduce((m, p) => { const [a, b] = p.split(':'); m[a] = b; return m; }, {});\n})(window.Gomoku = window.Gomoku || {});\n`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'voice-lexicon.js'), out);
console.log(`${lines.length} aliases, ${out.length} bytes`);
